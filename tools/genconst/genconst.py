#!/usr/bin/env python3
"""Generate mt5/constants_gen.go from the official MetaTrader5 Python package.

The constant block at the top of MetaTrader5/__init__.py (MIT, (c) MetaQuotes)
is the source of truth, so the Go values match the Python package exactly.

Usage (the wheel only needs to be unpacked, not installed):
    pip download --no-deps --only-binary=:all: --platform win_amd64 \
        --python-version 3.12 MetaTrader5 -d /tmp/mt5whl
    unzip -o /tmp/mt5whl/*.whl -d /tmp/mt5whl/x
    python3 -I tools/genconst/genconst.py /tmp/mt5whl/x/MetaTrader5/__init__.py > mt5/constants_gen.go
    gofmt -w mt5/constants_gen.go
"""
import re
import sys

# Longest prefix first. Value is the Go type; None means untyped int constant.
TYPES = [
    ("TIMEFRAME_", "Timeframe"),
    ("COPY_TICKS_", "CopyTicksFlag"),
    ("TICK_FLAG_", "TickFlag"),
    ("POSITION_TYPE_", "PositionType"),
    ("POSITION_REASON_", "PositionReason"),
    ("ORDER_TYPE_", "OrderType"),
    ("ORDER_STATE_", "OrderState"),
    ("ORDER_FILLING_", "OrderFilling"),
    ("ORDER_TIME_", "OrderTypeTime"),
    ("ORDER_REASON_", "OrderReason"),
    ("DEAL_TYPE_", "DealType"),
    ("DEAL_DIVIDEND", "DealType"),
    ("DEAL_TAX", "DealType"),
    ("DEAL_ENTRY_", "DealEntry"),
    ("DEAL_REASON_", "DealReason"),
    ("TRADE_ACTION_", "TradeAction"),
    ("TRADE_RETCODE_", "TradeRetcode"),
    ("RES_", "ResultCode"),
]

LINE = re.compile(r"^([A-Z][A-Z0-9_]*)\s*=\s*([^#]+?)\s*(?:#\s*(.*))?$")


def camel(name: str) -> str:
    return "".join(p[:1] + p[1:].lower() if not p.isdigit() else p for p in name.split("_"))


def gotype(name: str):
    for prefix, t in TYPES:
        if name.startswith(prefix):
            return t
    return None


def main(path: str) -> None:
    out = [
        "// Code generated by tools/genconst/genconst.py from the MetaTrader5 Python package; DO NOT EDIT.",
        "",
        "package mt5",
        "",
    ]
    version = "unknown"
    with open(path, encoding="utf-8") as f:
        lines = f.read().splitlines()
    for raw in lines:
        if raw.startswith("from ._core"):
            break
        m = re.match(r"^__version__\s*=\s*'([^']+)'", raw)
        if m:
            version = m.group(1)
            continue
        if raw.startswith("#"):
            out.append("// " + raw.lstrip("# ").strip())
            continue
        m = LINE.match(raw.strip())
        if not m or m.group(1).startswith("__"):
            continue
        name, expr, comment = m.group(1), m.group(2).strip(), m.group(3)
        t = gotype(name)
        line = f"const {camel(name)}"
        line += f" {t} = {expr}" if t else f" = {expr}"
        if comment:
            line += " // " + comment.strip()
        out.append(line)
    out.insert(1, f"// Source: MetaTrader5 {version}.")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
